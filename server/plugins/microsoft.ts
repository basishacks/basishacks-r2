import { env } from "node:process";

const metadata = {
    access_token: null
}

export default async function initializeMSAccessToken() {

    if (metadata.access_token) {
        console.log("MS Access Token already initialized")
        return metadata.access_token;
    }

    const req = await fetch("https://login.microsoftonline.com/cbc6e1e2-a6bb-4002-bbdc-6da892a051a7/oauth2/v2.0/token",{
        method: "POST",
        headers: {
            'Content-Type': 'application/x-www-form-urlencoded'
        },
        body: encodeURI(
            "client_id=868b989e-6574-4795-bcfb-8db37bee1c37&" +
            "scope=https://graph.microsoft.com/.default&" +
            "client_secret=" + env.MICROSOFT_CLIENT_SECRET + "&" +
            "grant_type=client_credentials"
        )
    })

    const code = req.status;
    const data: any = await req.json();
    console.log("Response from MS Token Endpoint: " + code);

    return metadata.access_token = data.access_token;
}

export function getMSAccessToken() {
    if (!metadata.access_token) {
        throw new Error("MS Access Token not initialized")
    }
    return metadata.access_token;
}

