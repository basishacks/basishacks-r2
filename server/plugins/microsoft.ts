async function requestMicrosoft(endpoint: string, method: string = "GET", body: any = null) {

    const res = await fetch("https://graph.microsoft.com/v1.0" + endpoint, {
        method,
        headers: {
            "Content-Type": "application/json",
            "Authorization": "Bearer " + getMSAccessToken()
        },
        body
    });

    return res;
}

export async function createMicrosoftMeeting(target: string, subject: string, htmlDescription: string, startTime: string, endTime: string, attendees: any[]): Promise<Response> {

    const disclaimer = `<br><br><hr><p style='font-size:10pt;color:gray;'><i>This event was auto-generated by basishacks. If you believe this was scheduled in error or need to reschedule, please feel free to direct message devclub-bisz@basischina.com and your message will be fowarded to the necessary person.</i></p>`

    const body = JSON.stringify({
        "subject": subject,
        "body" : {
            "contentType": "HTML",
            "content": htmlDescription + disclaimer
        },
        "start": {
            "dateTime": startTime,
            "timeZone": "UTC"
        },
        "end": {
            "dateTime": endTime,
            "timeZone": "UTC"
        },
        "attendees": attendees.map(email => ({
            "emailAddress": {
                "address": email
            }
        }))
    });

    const res = await requestMicrosoft("/users/" + target + "/events", "POST", body);

    return res; // Created
}

